def detect_language(default="en"):
    """LASERCUT_LANG, sinon langue du système, sinon `default`."""
    env = os.environ.get("LASERCUT_LANG")
    if env:
        return env[:2].lower()
    for var in ("LC_ALL", "LC_MESSAGES", "LANG"):
        val = os.environ.get(var)
        if val and val.split(".")[0] not in ("C", "POSIX"):
            return val[:2].lower()
    try:
        loc = locale.getlocale()[0]
        if loc and loc not in ("C", "POSIX"):
            return loc[:2].lower()
    except Exception:
        pass
    return default


def available_languages():
    langs = {"en"} | set(_BUILTIN)
    try:
        langs |= {f[:-5] for f in os.listdir(_LOCALES_DIR) if f.endswith(".json")}
    except OSError:
        pass
    return sorted(langs)


def set_language(lang):
    """Charge le catalogue. Retourne la langue réellement active."""
    global _catalog, _lang
    lang = (lang or "en")[:2].lower()
    cat = load_catalog(lang)
    if cat or lang == "en":
        _catalog, _lang = cat, lang
    else:
        _catalog, _lang = {}, "en"
    return _lang


def load_catalog(lang):
    """Catalogue brut d'une langue (dict). Vide si inconnue ou 'en'."""
    lang = (lang or "en")[:2].lower()
    try:
        with open(os.path.join(_LOCALES_DIR, f"{lang}.json"), encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return dict(_BUILTIN.get(lang, {}))


