def tr(text, **kwargs):
    """Traduit `text` puis applique str.format(**kwargs) si fourni."""
    out = _catalog.get(text, text)
    if kwargs:
        try:
            out = out.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            out = text.format(**kwargs)
    return out
